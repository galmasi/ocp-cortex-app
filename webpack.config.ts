import { Configuration } from 'webpack';
import webpack from 'webpack';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { ConsoleRemotePlugin } from '@openshift-console/dynamic-plugin-sdk-webpack';

// Read package.json directly — importing JSON needs import attributes
// under ESM ts-node, which is more friction than a file read.
const pkg = JSON.parse(
  readFileSync(new URL('./package.json', import.meta.url), 'utf8'),
);

/**
 * The ConsoleRemotePlugin scans the code for consolePlugin() calls and
 * generates dist/plugin-manifest.json, which the console reads to learn
 * which extensions this plugin provides and which bundle to load.
 */
const config: Configuration = {
  mode: 'production',
  // All entries are generated by ConsoleRemotePlugin from the
  // `consolePlugin.exposedModules` field in package.json (module federation).
  entry: {},
  module: {
    rules: [
      {
        test: /\.tsx?$/,
        exclude: /node_modules/,
        use: {
          loader: 'ts-loader',
          options: {
            transpileOnly: true,
          },
        },
      },
      {
        // Includes node_modules — xterm.js ships its own CSS.
        test: /\.css$/,
        use: ['style-loader', 'css-loader'],
      },
    ],
  },
  resolve: {
    extensions: ['.tsx', '.ts', '.js'],
  },
  output: {
    // Bundle straight into the plugin image's build context so the
    // Dockerfile there is self-contained (podman build cortex-plugin-image).
    path: fileURLToPath(new URL('./cortex-plugin-image/dist', import.meta.url)),
    filename: '[name]-bundle.js',
    // 'auto' lets the plugin bundle be served from any path, which is what
    // makes local dev (webpack-dev-server) and in-cluster (nginx) both work.
    publicPath: 'auto',
  },
  plugins: [
    // Bake the plugin version into the bundle at build time so the page
    // can display it — the single source of truth is package.json's
    // consolePlugin.version, which must be bumped every deploy anyway.
    new webpack.DefinePlugin({
      CORTEX_PLUGIN_VERSION: JSON.stringify(pkg.consolePlugin.version),
    }),
    new ConsoleRemotePlugin(),
  ],
  devtool: 'source-map',
};

export default config;
